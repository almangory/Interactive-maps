export const useLanguage = (): LanguageContextType => {
  const context = useContext(LanguageContext);
  if (!context) {
    // Fallback if rendered outside provider
    return {
      language: 'ar',
      setLanguage: () => {},
      toggleLanguage: () => {},
      isRtl: true,
      t: (k, fb) => (typeof fb === 'string' ? fb : k),
      translateDynamic: (txt) => txt,
      formatNumber: (n) => String(n)
    };
  }
  return context;
};

